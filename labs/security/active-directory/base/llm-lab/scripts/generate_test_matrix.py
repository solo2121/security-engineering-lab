#!/usr/bin/env python3
"""Regenerate docs/test-matrix.md from the test names.

Test functions are named test_llmNN_2026_<what>, test_lab_llmNN_2026_<what>,
test_xcut_<what> or test_<what>. The risk comes from the NN, the description
from the rest of the name. Run with --check to fail when the file is stale.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "test-matrix.md"
RISKS = {
    "01": "LLM01 Prompt Injection", "02": "LLM02 Sensitive Information Disclosure",
    "03": "LLM03 Excessive Agency", "04": "LLM04 Supply Chain", "05": "LLM05 Data and Model Poisoning",
    "06": "LLM06 Unbounded Consumption", "07": "LLM07 Misinformation", "08": "LLM08 Hidden Context Exposure",
    "09": "LLM09 Vector and Embedding Weaknesses", "10": "LLM10 Improper Output Handling",
}
HEADER = """# Test matrix

Generated by `scripts/generate_test_matrix.py` from the test names. Every row
is a test in `tests/`; the pass criterion is the same for all: it passes in CI
(`pytest tests/ -v`), and a failure means the control or the lab behavior
regressed. Rows marked "lab" prove an intentionally vulnerable behavior still
works, so the attack stays teachable.

The 33 original scenario tests in `tests/test_app.py` cover the vulnerable
modules under the 2025 endpoint numbering and are not listed here.

| Test | Risk | What it checks |
|---|---|---|
"""


def rows() -> list[str]:
    out = []
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        if path.name == "test_app.py":
            continue
        for name in re.findall(r"^def (test_\w+)\(", path.read_text(), re.M):
            m = re.match(r"test_(lab_)?llm(\d\d)_2026_(.*)", name)
            if m:
                risk = RISKS[m.group(2)] + (" (lab)" if m.group(1) else "")
                what = m.group(3)
            elif name.startswith("test_xcut_"):
                risk, what = "Cross-cutting hardening", name[len("test_xcut_"):]
            elif name.startswith("test_ollama_") or name.startswith("test_provider_"):
                risk, what = "Model provider (fake Ollama server)", re.sub(r"^test_", "", name)
            else:
                risk, what = "Run modes and structure", name[len("test_"):]
            out.append(f"| `{name}` | {risk} | {what.replace('_', ' ')} |")
    return out


def render() -> str:
    return HEADER + "\n".join(rows()) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(rows())} rows)")
